"""Reserve and wake the pipeline Atlas cluster.

This is the reviewed operator entrypoint for a manual pipeline reservation.
Cluster lifecycle behavior remains in ``pipeline.run_lifecycle``; this file
only loads the local environment, creates the reservation, wakes the cluster,
and reports the resulting state.
"""

from __future__ import annotations

import argparse
import sys
import uuid
from datetime import datetime, timezone
from pathlib import Path


_ROOT = Path(__file__).resolve().parents[3]
for _path in (_ROOT, _ROOT / "ChatHealthyLib" / "src"):
    if str(_path) not in sys.path:
        sys.path.insert(0, str(_path))

from pipeline.run_lifecycle.cluster_lifecycle_manager import (  # noqa: E402
    ClusterLifecycleManager,
)
from pipeline.run_lifecycle.pipeline_env import load_pipeline_env  # noqa: E402
from chathealthy_lib.exceptions import ChatHealthyException  # noqa: E402
from chathealthy_lib.logging_service import ChatHealthyLoggingService  # noqa: E402


_log = ChatHealthyLoggingService()


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Create a human reservation and wake the pipeline cluster."
    )
    parser.add_argument(
        "--cluster",
        default="ChatHealthyDataPipelines",
        help="Atlas cluster name (default: ChatHealthyDataPipelines).",
    )
    parser.add_argument(
        "--hours",
        type=int,
        default=3,
        help="Reservation duration in whole hours (default: 3).",
    )
    parser.add_argument(
        "--requester",
        default="operator_manual",
        help="Audit requester name (default: operator_manual).",
    )
    parser.add_argument(
        "--job-id",
        default=None,
        help="Optional reservation ID; a unique one is generated by default.",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    if args.hours <= 0:
        raise ChatHealthyException(
            mode="invalid_argument",
            message="--hours must be a positive whole number",
            component="reserve_pipeline_cluster",
        )

    load_pipeline_env()
    job_id = args.job_id or (
        f"manual-hold-{datetime.now(timezone.utc):%Y%m%dT%H%M%SZ}-"
        f"{uuid.uuid4().hex[:10]}"
    )
    duration_minutes = args.hours * 60

    manager = ClusterLifecycleManager(get_db_fn=lambda: None, env_prefix="dev")
    reservation = manager.reserve(
        cluster_name=args.cluster,
        job_id=job_id,
        requester=args.requester,
        expected_duration_minutes=duration_minutes,
        reservation_class="human",
    )

    # Write the reservation before waking the cluster so the reaper sees a
    # valid hold throughout the resume operation.
    manager.wake(args.cluster, job_id=job_id)
    status = manager.status(args.cluster, job_id=job_id)

    _log.LogPipeline(
        "INFO",
        "RESERVED: %s | expiry_at=%s | duration_hours=%d",
        reservation["_id"],
        reservation["expiry_at"],
        args.hours,
    )
    _log.LogPipeline(
        "INFO",
        "CLUSTER_STATE: %s | active_reservations=%d",
        status["cluster_state"],
        status["active_reservations"],
    )
    return 0


if __name__ == "__main__":
    main()
